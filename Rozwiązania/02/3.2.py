# W oryginalnym programie dodawane są dwie liczby. Musimy dodać trzecią zmienną number3 i uwzględnić ją w obliczeniu.
# A program that calculates the sum of three numbers.
# Program oblicza sumę trzech liczb.

# Przypisujemy pierwszą liczbę do zmiennej number1.
number1 = 71

# Przypisujemy drugą liczbę do zmiennej number2.
number2 = 14

# Przypisujemy trzecią liczbę do zmiennej number3.
number3 = 10

# Dodajemy do siebie trzy liczby i zapisujemy wynik.
# result - zmienna przechowująca wynik dodawania trzech liczb.
result = number1 + number2 + number3

# print() wyświetla tekst oraz wartość pierwszej liczby.
print('Number 1: ', number1)

# Wyświetlamy drugą liczbę.
print('Number 2: ', number2)

# Wyświetlamy trzecią liczbę.
print('Number 3: ', number3)

# Wyświetlamy obliczoną sumę.
print('The result of summation: ', result)