# Aby zamienić prędkość z kilometrów na godzinę (km/h) na metry na sekundę (m/s), dzielimy ją przez 3.6.
# W zadaniu prędkość wynosi 70 km/h.
# A program that converts speed from km/h to m/s.
# Program zamienia prędkość z km/h na m/s.

# Zapisujemy prędkość w kilometrach na godzinę.
speed_kmh = 70

# Dzielimy prędkość przez 3.6, aby otrzymać wynik w m/s.
speed_ms = speed_kmh / 3.6

# Wyświetlamy prędkość przed i po przeliczeniu.
print(speed_kmh, "km/h = ", speed_ms, "m/s")