# W tym zadaniu mamy dwie zmienne: a = 3 i b = 5. Program ma wyświetlić działania oraz ich wyniki.

# A program that prints mathematical expressions and their results.
# Program wyświetla działania matematyczne i ich wyniki.

# Przypisujemy wartości do zmiennych.
a = 3
b = 5

# Wyświetlamy dodawanie i jego wynik.
# f"..." – tworzy f-string, czyli tekst, w którym można umieszczać wartości zmiennych w nawiasach {}.
# {a}, {b} – wstawiają wartości zmiennych do f-stringa.
print(f'{a}+{b}={a + b}')

# Wyświetlamy odejmowanie i jego wynik.
print(f'{a}-{b}={a - b}')

# Wyświetlamy mnożenie i jego wynik.
print(f'{a}*{b}={a * b}')

# Wyświetlamy dzielenie i jego wynik.
print(f'{a}/{b}={a / b}')