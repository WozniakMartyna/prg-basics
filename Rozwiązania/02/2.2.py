# Operator to symbol wykonujący działanie, np. +, *, **.
# Argument to wartość, na której wykonywane jest działanie, np. liczba 3 lub 2.

3 * 2 + 1
# Operatory: 2
# Argumenty: 3
# Wynik: 7

5 + 10 * 5
# Operatory: 2
# Argumenty: 3
# Wynik: 55

4 + 4 / 2 ** 2
# Operatory: 3
# Argumenty: 4
# Wynik: 5.0

4 % 3 % 2 % 1
# Operatory: 3
# Argumenty: 4
# Wynik: 0

1 + 2 % 3 ** 4 * 5
# Operatory: 4
# Argumenty: 5
# Wynik: 11

True != False
# Operatory: 1
# Argumenty: 2
# != sprawdza, czy wartości są różne np. True != False daje True
# Wynik: True