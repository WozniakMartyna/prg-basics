# if oznacza jeżeli — wykonaj kod, jeśli warunek jest prawdziwy.
# else oznacza w przeciwnym razie — wykonaj kod, jeśli warunek jest fałszywy.

# Sprawdzamy, czy osoba jest pełnoletnia.
age = 10  # Zmienna przechowuje wiek osoby.

if age >= 18:  # Sprawdzamy, czy wiek jest większy lub równy 18.
    print('You are an adult.')  # Ten komunikat pojawi się, jeśli warunek jest prawdziwy.
else:  # W przeciwnym razie wykonujemy kod poniżej.
    print('You are not an adult.')  # Ten komunikat pojawi się, jeśli warunek jest fałszywy.

# if sprawdza warunek.
# else wykonuje się, gdy warunek przy if jest fałszywy.
# Dwukropek : rozpoczyna blok kodu.
# Wcięcie (spacje przed print) pokazuje, które instrukcje należą do if lub else.