# W zadaniu należy zmodyfikować program tak, aby tekst Practice makes perfect! wyświetlał się sześć razy zamiast czterech.

# range(6) tworzy sześć kolejnych wartości: od 0 do 5.
# Pętla for wykona się więc sześć razy.
# Zmienna i przyjmuje kolejne wartości z tego zakresu.
for i in range(6):
    # print() wyświetla tekst podczas każdego powtórzenia pętli.
    print('Practice makes perfect!')

# for rozpoczyna pętlę, która powtarza instrukcje.
# i jest zmienną przechowującą kolejne wartości zakresu.
# in wskazuje zakres, po którym przechodzi pętla.
# Wcięcie oznacza, że print() należy do pętli.